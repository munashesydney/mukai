export type CapabilityKind = 'tool' | 'route' | 'job';
export type CustomJobTrigger =
  | { type: 'interval'; intervalMs: number }
  | { type: 'workspace_start' }
  | { type: 'once'; runAt: string };
export interface CustomJobEvent {
  trigger: 'interval' | 'workspace_start' | 'once' | 'manual';
  scheduledAt: string;
  runtimeId?: string;
}

/** Authoring contract for real .ts/.js capability modules. Imports may be type-only. */
export const customToolPermissionModes = ['auto_approve', 'ask_bot', 'user_approval'] as const;
export type CustomToolPermissionMode = (typeof customToolPermissionModes)[number];
/** Generated by Mukai's runtime; custom module output is nested under result. */
export interface CustomToolReceipt {
  permission: {
    mode: CustomToolPermissionMode;
    approvedBy: 'user' | 'bot' | 'runtime';
    decision: 'approved' | 'auto_approved' | 'denied' | 'cancelled';
  };
  execution: 'completed' | 'failed' | 'not_executed';
  result?: unknown;
  error?: string;
  rejected?: boolean;
  cancelled?: boolean;
  message?: string;
}
export const customToolPermissionLabels: Record<CustomToolPermissionMode, string> = {
  auto_approve: 'Auto approve',
  ask_bot: 'Ask bot',
  user_approval: 'User approval',
};
export interface CustomRouteCallRequest {
  /** JSON request body. Mutually exclusive with rawBody. */
  body?: unknown;
  /** Exact UTF-8 request text, useful for signed webhooks. */
  rawBody?: string;
  headers?: Record<string, string>;
  query?: Record<string, string>;
}
export interface CapabilityContext {
  env: Record<string, string>;
  signal: AbortSignal;
  workspaceId: string;
  /** Absolute workspace root on the computer executing this module. */
  workspacePath: string;
  /** Commit a job before acknowledging a webhook. Duplicate event IDs return the same job. */
  enqueue(
    provider: string,
    eventId: string,
    payload: unknown,
  ): Promise<{ id: string; duplicate: boolean }>;
  /** Queue a model run for botId, or the registration's owner when omitted. */
  wakeBot(message: string, options?: { botId?: string }): Promise<{ accepted: boolean }>;
  /** Invoke a registered route in this workspace without handling Mukai credentials. */
  callRoute(routeId: string, request?: CustomRouteCallRequest): Promise<CustomResponse>;
}
export interface CustomToolModule {
  name: string;
  description: string;
  inputSchema: Record<string, unknown>;
  requiredEnv?: string[];
  timeoutMs?: number;
  execute(args: unknown, context: CapabilityContext): Promise<unknown> | unknown;
}
export interface CustomRequest {
  method: string;
  url: string;
  headers: Record<string, string | string[] | undefined>;
  rawBody: Uint8Array;
  body?: unknown;
}
export interface CustomResponse {
  status: number;
  headers?: Record<string, string>;
  body?: unknown;
}
export interface CustomRouteModule {
  name: string;
  method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE' | 'HEAD';
  path: string;
  /** handler: verify the provider signature before work/enqueue; public: explicitly unauthenticated. */
  auth: 'mukai' | 'handler' | 'public';
  requiredEnv?: string[];
  timeoutMs?: number;
  handle(
    request: CustomRequest,
    context: CapabilityContext,
  ): Promise<CustomResponse> | CustomResponse;
  processJob?(payload: unknown, context: CapabilityContext): Promise<unknown> | unknown;
}
export interface CustomJobModule {
  name: string;
  description: string;
  triggers: CustomJobTrigger[];
  requiredEnv?: string[];
  timeoutMs?: number;
  run(event: CustomJobEvent, context: CapabilityContext): Promise<unknown> | unknown;
  processJob?(payload: unknown, context: CapabilityContext): Promise<unknown> | unknown;
}
export interface CapabilityDefinition {
  triggers?: CustomJobTrigger[];
  permissionMode?: CustomToolPermissionMode;
  name: string;
  description?: string;
  inputSchema?: Record<string, unknown>;
  method?: string;
  path?: string;
  auth?: CustomRouteModule['auth'];
  requiredEnv: string[];
  timeoutMs: number;
  hasJobHandler: boolean;
}
export interface CapabilityRegistration {
  id: string;
  workspaceId: string;
  ownerBotId: string | null;
  kind: CapabilityKind;
  modulePath: string;
  exportName: string;
  version: string;
  enabled: boolean;
  definition: CapabilityDefinition;
  status: 'ready' | 'disabled' | 'needs_configuration' | 'invalid';
  missingEnv: string[];
  error: string | null;
  url?: string;
  urlNote?: string;
  nextRunAt?: string | null;
  health?: {
    lastRun: CapabilityRun | null;
    consecutiveFailures: number;
    lastError: string | null;
  };
}
export interface CapabilityRun {
  id: string;
  version: string;
  status: string;
  startedAt: string;
  durationMs: number | null;
  error: string | null;
}
export interface EnvironmentVariable {
  name: string;
  secret?: boolean;
  configured: boolean;
  usedBy: string[];
}
